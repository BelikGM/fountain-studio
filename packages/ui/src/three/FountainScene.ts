/**
 * Начальная скорость, при которой капля с ослабленной тяжестью g' = G·gScale и
 * линейным сопротивлением k поднимется РОВНО на заданную высоту.
 *
 * У обычной струи хватает школьного v₀ = √(2gh), но у водяной взвеси
 * сопротивление съедает больше половины подъёма, и, главное, съедает
 * НЕЛИНЕЙНО: подобранный на 2 м поправочный коэффициент на 8 м врёт вдвое.
 * Поэтому здесь решается точное уравнение движения. Интегрируя
 * dv/dt = −g' − k·v, получаем h(v₀) = (g'/k²)·(A − ln(1+A)), где A = k·v₀/g';
 * обратную задачу решаем Ньютоном (функция монотонна, сходится за единицы
 * итераций). Без этого «туман высотой 1 м» приходилось выставлять цифрой
 * 20–25 м — ровно то, на что и жаловались.
 */
function v0ForHeight(heightM: number, gScale: number, drag: number): number {
  const g = G * gScale;
  if (drag <= 0) return Math.sqrt(2 * g * heightM);
  const c = (heightM * drag * drag) / g;
  let a = c + Math.log(1 + c) + 1; // грубая начальная догадка сверху
  for (let i = 0; i < 40; i++) {
    const f = a - Math.log(1 + a) - c;
    const d = a / (1 + a); // производная
    if (d < 1e-9) break;
    const step = f / d;
    a = Math.max(1e-6, a - step);
    if (Math.abs(step) < 1e-9) break;
  }
  return (a * g) / drag;
}

/** Время подъёма до вершины для той же модели движения, с. */
function riseTimeSec(v0: number, gScale: number, drag: number): number {
  const g = G * gScale;
  if (drag <= 0) return v0 / g;
  return Math.log(1 + (drag * v0) / g) / drag;
}

