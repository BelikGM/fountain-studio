import type { ModbusPumpConfig } from './project';

/**
 * Готовые карты регистров преобразователей частоты.
 *
 * Зачем. Вписывать адреса регистров руками на объекте — верный способ ошибиться
 * и полдня искать, почему насос не слушается. У каждой серии ПЧ карта своя, но
 * их немного, и они известны: достаточно выбрать серию из списка, а дальше все
 * поля заполнятся сами.
 *
 * Почему «своя карта» осталась. Список закрытым быть не может: на объекте может
 * стоять что угодно, вплоть до снятого с производства. Поэтому пресет — это
 * просто заполнение полей, каждое из которых потом правится руками. Незнакомый
 * ПЧ не блокирует работу: берём «свою карту» и вписываем адреса из его паспорта.
 *
 * Про достоверность. У каждой записи честно помечено, откуда взяты адреса и
 * проверялись ли они на живом приводе, — чтобы на объекте было понятно, чему
 * доверять без проверки, а что стоит сверить с паспортом.
 */

export interface VfdPreset {
  id: string;
  /** Как показывать в списке — коротко, чтобы влезало. */
  label: string;
  /** Откуда карта и насколько ей можно верить. */
  note: string;
  /** Поля, которыми заполняется настройка насоса. */
  map: Pick<
    ModbusPumpConfig,
    | 'freqRegister'
    | 'freqRegScale'
    | 'cmdRegister'
    | 'faultRegister'
    | 'currentRegister'
    | 'currentScale'
    | 'speedRegister'
    | 'speedScale'
    | 'tempRegister'
    | 'tempScale'
  >;
}

