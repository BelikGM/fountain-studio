/**
 * Лицензия (§27 доработки, раздел «Продукт») — привязка к 1 ПК: подписанный
 * офлайн-файл, без облачного сервера (тот потребовался бы для привязки к
 * аккаунту — отдельный проект). Подпись — Ed25519 через встроенный в Node
 * crypto, без внешней зависимости. Проверка целиком на стороне движка (см.
 * packages/engine/src/license.ts) — редактор только показывает статус и
 * шлёт содержимое файла на активацию.
 */

/** Уровень подписки — что открывает выданная лицензия (см. AccessLevel ниже). */
export type LicensePlan = 'pro' | 'max';

/** То, что реально подписывается — порядок полей фиксирован (см. canonicalPayload в engine/license.ts). */
export interface LicensePayload {
  licenseeName: string;
  /** sha256 отпечатка машины (см. machineFingerprint в engine/license.ts). */
  machineId: string;
  issuedAt: string;
  /** null — бессрочная лицензия. */
  expiresAt: string | null;
  /**
   * Уровень подписки. Отсутствует у лицензий, выпущенных до появления
   * уровней (18.09.2026) — такие считаем max: раньше лицензия была
   * «всё включено», принудительно понижать задним числом не за что.
   */
  plan?: LicensePlan;
}

export interface LicenseFile {
  payload: LicensePayload;
  /** Ed25519-подпись payload, base64. */
  signature: string;
}

/**
 * Что реально открыто в редакторе — не то же самое, что «есть валидная
 * лицензия». Три уровня:
 *
 *  · none — лицензии не было НИКОГДА (совсем новая установка): доступен
 *    только экран приветствия с ценами и контактами, ни одной рабочей
 *    вкладки. Человек ничего не терял — ему просто ещё не открыли доступ.
 *  · pro  — воспроизведение и «текущая эксплуатация»: плейлисты, шоу,
 *    расписание. Понижаем сюда ЛЮБУЮ лицензию, которая истекла или была
 *    отозвана, — фонтан не должен резко остаться совсем без управления
 *    из-за забытого продления: он продолжает играть по расписанию то, что
 *    уже настроено, просто новое завести или поменять схему нельзя.
 *  · max  — полный доступ: разработка шоу, 3D-схема, оборудование,
 *    протоколы, диагностика.
 */
export type AccessLevel = 'none' | 'pro' | 'max';

export interface LicenseStatus {
  licensed: boolean;
  licenseeName: string | null;
  expiresAt: string | null;
  /** Отпечаток ЭТОГО компьютера — показываем оператору, чтобы он мог отправить его для выпуска лицензии. */
  machineId: string;
  /** Причина отказа, когда licensed=false (нет файла / не тот ПК / истекла / подпись не сходится / отозвана). */
  reason?: string;
  /** Что реально доступно в редакторе — см. AccessLevel. Считается движком по правилам понижения выше. */
  access: AccessLevel;
  /** Уровень ДЕЙСТВУЮЩЕЙ лицензии (если licensed=true) — для экрана лицензии и подсказок «на что менять». null, если сейчас ничего не активно. */
  plan: LicensePlan | null;
}
