/**
 * Лицензия (§27 доработки, раздел «Продукт») — привязка к 1 ПК: подписанный
 * офлайн-файл, без облачного сервера (тот потребовался бы для привязки к
 * аккаунту — отдельный проект). Подпись — Ed25519 через встроенный в Node
 * crypto, без внешней зависимости. Проверка целиком на стороне движка (см.
 * packages/engine/src/license.ts) — редактор только показывает статус и
 * шлёт содержимое файла на активацию.
 */

/** Уровень подписки — что открывает выданная лицензия (см. AccessLevel ниже). */
export type LicensePlan = 'pro' | 'max';

/** То, что реально подписывается — порядок полей фиксирован (см. canonicalPayload в engine/license.ts). */
export interface LicensePayload {
  licenseeName: string;
  /** sha256 отпечатка машины (см. machineFingerprint в engine/license.ts). */
  machineId: string;
  issuedAt: string;
  /** null — бессрочная лицензия. */
  expiresAt: string | null;
  /**
   * Уровень подписки. Отсутствует у лицензий, выпущенных до появления
   * уровней (18.09.2026) — такие считаем max: раньше лицензия была
   * «всё включено», принудительно понижать задним числом не за что.
   */
  plan?: LicensePlan;
}

export interface LicenseFile {
  payload: LicensePayload;
  /** Ed25519-подпись payload, base64. */
  signature: string;
}

/**
 * Что реально открыто в редакторе — не то же самое, что «есть валидная
 * лицензия». Три уровня:
 *
 *  · none — действующей лицензии нет: совсем новая установка, истёкшая
 *    подписка или отозванная лицензия. Доступен только экран приветствия с
 *    ценами и контактами, ни одной рабочей вкладки. Решение заказчика от
 *    18.09.2026: не оплачен даже самый дешёвый тариф — программа не
 *    работает (иначе после первой оплаты человек бессрочно пользуется
 *    уровнем Pro даром).
 *  · pro  — ДЕЙСТВУЮЩАЯ подписка Pro: воспроизведение и текущая
 *    эксплуатация — плейлисты, шоу, расписание.
 *  · max  — полный доступ: разработка шоу, 3D-схема, оборудование,
 *    протоколы, диагностика.
 */
export type AccessLevel = 'none' | 'pro' | 'max';

export interface LicenseStatus {
  licensed: boolean;
  licenseeName: string | null;
  expiresAt: string | null;
  /** Отпечаток ЭТОГО компьютера — показываем оператору, чтобы он мог отправить его для выпуска лицензии. */
  machineId: string;
  /** Причина отказа, когда licensed=false (нет файла / не тот ПК / истекла / подпись не сходится / отозвана). */
  reason?: string;
  /** Что реально доступно в редакторе — см. AccessLevel. Считается движком по правилам выше. */
  access: AccessLevel;
  /**
   * Подпись настоящая и лицензия для ЭТОГО компьютера — просто вышел срок
   * (и льготные дни тоже). Доступ при этом такой же, как без лицензии
   * (none), но интерфейсу важно отличать: человеку с истёкшей подпиской
   * говорим «продлите», а не «выберите тариф» — он уже выбирал и платил.
   */
  expired?: boolean;
  /**
   * Срок вышел, но идут льготные дни (GRACE_PERIOD_DAYS): программа ещё
   * работает в полном объёме, интерфейс настойчиво просит оплатить.
   * graceDaysLeft — сколько таких дней осталось.
   */
  grace?: boolean;
  graceDaysLeft?: number;
  /** Уровень ДЕЙСТВУЮЩЕЙ лицензии (если licensed=true) — для экрана лицензии и подсказок «на что менять». null, если сейчас ничего не активно. */
  plan: LicensePlan | null;
}

/**
 * За сколько дней до конца начинаем предупреждать в интерфейсе.
 *
 * Две недели — компромисс: месяц назойливо (плашка висит треть срока
 * месячной подписки), а за пару дней человек уже может не успеть списаться
 * и оплатить. У продавца свой срок — `issue-license.ts list` показывает
 * «требуют внимания» за 30 дней, чтобы успеть написать первым.
 */
export const EXPIRY_WARNING_DAYS = 14;

/**
 * Льготный период после даты окончания: программа ещё работает, но уже
 * настойчиво просит оплатить. Нужен, чтобы человек не оставался с мёртвым
 * фонтаном из-за задержки платежа на пару дней — оплата редко проходит день
 * в день.
 *
 * ВАЖНО, и это не случайность: продление считается от ИСХОДНОЙ даты
 * окончания, а не от дня оплаты (см. --renew в issue-license.ts). Оплатил
 * 17-го при сроке до 10-го — новый срок до 10-го следующего месяца, а не до
 * 17-го. Иначе выгодно платить с опозданием, и льгота превращается в
 * бесплатную неделю каждый месяц.
 */
export const GRACE_PERIOD_DAYS = 7;

/**
 * Сколько полных дней осталось до конца лицензии; null — бессрочная или
 * даты нет. Отрицательное — уже истекла столько дней назад.
 *
 * Считается от системных часов, как и сама проверка срока в движке: если
 * часы на объекте переведут назад, «продлится» и лицензия, и это
 * предупреждение — честная цена офлайновой модели без сервера времени.
 */
export function daysUntilExpiry(expiresAt: string | null, nowMs = Date.now()): number | null {
  if (!expiresAt) return null;
  const end = new Date(expiresAt).getTime();
  if (Number.isNaN(end)) return null;
  return Math.floor((end - nowMs) / 86_400_000);
}
