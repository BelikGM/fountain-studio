/**
 * Калибр капли струи и то, насколько её цепляет ветер. ОДНА модель на всю
 * программу: по ней и рисуется снос в 3D, и режутся насосы ветровым
 * ограничением.
 *
 * ── Зачем это вынесено из 3D ──────────────────────────────────────────────
 * Раньше было два разных расчёта. В визуализации калибр капли считался для
 * КАЖДОЙ форсунки по диаметру сопла и распылению, а коэффициент сцепки был
 * подобран по замерам с объекта (заказчик, 15.09.2026: пятиметровую прямую
 * струю 20 мм при ветре 15 м/с сносит примерно на 2 м, десятиметровую —
 * на 4–5 м). А ветровое ограничение считало по ОДНОМУ числу на весь объект,
 * τ = 4 с, и давало для той же струи снос 6,5 м — втрое больше замеренного.
 *
 * Расходились они не в мелочи: ограничение резало струи заметно раньше и
 * сильнее, чем требует реальность, а картинка в 3D показывала другое. Теперь
 * модель одна и живёт здесь.
 *
 * ── Из чего складывается ──────────────────────────────────────────────────
 * 1. КАЛИБР КАПЛИ по типу форсунки и диаметру сопла (`nozzleDropM`). Капля
 *    соразмерна соплу: у ламинарной 2 мм она не может быть 30 мм. Распыление
 *    калибр мельчит — вода, уже разбитая в сопле, летит облаком.
 * 2. АЭРОДИНАМИЧЕСКИЙ диаметр (`airDropM`) — тот же калибр с потолком около
 *    6 мм: свободно летящая капля крупнее разваливается набегающим воздухом
 *    (тот же предел, по которому и дождевые капли не бывают больше). Подходим
 *    к потолку плавно, через тангенс: жёсткая отсечка стирала разницу между
 *    соплами 8 и 30 мм.
 * 3. ПОПРАВКА НА СКОРОСТЬ (`speedDropFactor`) — высокая струя бьёт быстрее, и
 *    вода рвётся на капли мельче, поэтому её сносит сильнее, чем только за
 *    счёт более долгого полёта. Без этой поправки десятиметровую струю сносило
 *    ровно вдвое дальше пятиметровой (3,8 м против 2), а на объекте — 4–5 м.
 * 4. СЦЕПКА С ВЕТРОМ (`windGripPerSec`) — насколько быстро капля догоняет
 *    скорость воздуха. Сила сопротивления идёт с площади (d²), масса с объёма
 *    (d³), поэтому ускорение ∝ 1/d: пыль сдувает сразу, плотную струю почти
 *    нет.
 *
 * Итог — `jetWindTauSec`: постоянная времени разгона воды ветром, секунды.
 * Именно она стоит в формуле сноса (`windlimit.ts`).
 */

import { clampSpray, type NozzleKind } from './layout';


/**
 * Калибр капли по типу форсунки: во сколько раз крупнее диаметра сопла и ниже
 * какого предела не опускаем.
 *
 * Значения перенесены из визуализации без изменений — они подбирались по тому,
 * как струя выглядит на объекте, и менять их здесь нельзя: поедет картинка.
 */
export const NOZZLE_DROP: Record<NozzleKind, { scale: number; minM: number }> = {
  straight: { scale: 1.1, minM: 0.003 },
  // Ламинарная — стеклянный шнур, воздуха внутри нет, капля мельче сопла.
  laminar: { scale: 0.8, minM: 0.003 },
  fan: { scale: 0.5, minM: 0.004 },
  canopy: { scale: 1.2, minM: 0.003 },
  flower: { scale: 1.2, minM: 0.003 },
  veil: { scale: 0.8, minM: 0.004 },
  /**
   * Туман — не струя воды, а водяная пыль: у каталожных распыляющих головок
   * капля не крупнее миллиметра. Отсюда и калибр задан почти жёстко.
   */
  mist: { scale: 0.03, minM: 0.0009 },
  // Пенная: воздух подмешан, «капля» крупнее сопла.
  foam: { scale: 1.6, minM: 0.003 },
  rotating: { scale: 1.1, minM: 0.003 },
  orbit: { scale: 1.0, minM: 0.003 },
  // Вариативная в собранном положении — это прямая струя, и капля та же.
  variable: { scale: 1.1, minM: 0.003 },
};

/** Верхний предел калибра капли, м — дальше частица перестаёт читаться струёй. */
const DROP_MAX_M = 0.08;

/**
 * Геометрический калибр капли, м — по типу форсунки, диаметру сопла и
 * распылению. Это то, что видно глазом в 3D.
 */
export function nozzleDropM(kind: NozzleKind, widthM: number, sprayFactor: number): number {
  const d = NOZZLE_DROP[kind];
  const spray = clampSpray(kind, sprayFactor);
  return Math.min(DROP_MAX_M, Math.max(d.minM, widthM * d.scale * (0.7 + 0.9 * spray)));
}

/**
 * Аэродинамический диаметр капли, м — тот же калибр с плавным потолком.
 *
 * Потолок не выдуман: свободно летящая капля крупнее примерно 6 мм неустойчива
 * и разваливается набегающим воздухом — тот самый предел, по которому и
 * дождевые капли не бывают больше. Распыление калибр мельчит: вода, уже
 * разбитая в сопле, сдувается охотнее при той же толщине струи.
 *
 * Подходим к потолку ПЛАВНО (гиперболический тангенс), а не отрезаем по нему.
 * Жёсткое ограничение стирало разницу между соплами: и 8 мм, и 30 мм упирались
 * в один калибр и получали одинаковый снос, хотя тонкая струя парусит заметно
 * сильнее толстой.
 */
export function airDropM(dropM: number, sprayFactor: number): number {
  const dMax = 0.006;
  const raw = Math.max(0.0002, dropM * (1.25 - 0.5 * sprayFactor));
  return Math.max(0.0005, dMax * Math.tanh(raw / dMax));
}

/** Скорость воды пятиметровой струи, м/с — опорная для поправки на скорость. */
export const WIND_DROP_V_REF = 9.9;
const WIND_DROP_V_POW = 0.35;

/**
 * Поправка калибра на скорость вылета: высокая струя бьёт быстрее, вода рвётся
 * на капли мельче, и сносит её сильнее, чем только за счёт долгого полёта.
 * Границы 0,5…1,6 — чтобы поправка не уходила в бесконечность на крайних
 * значениях.
 */
export function speedDropFactor(v0: number): number {
  return Math.min(1.6, Math.max(0.5, Math.pow(WIND_DROP_V_REF / Math.max(1, v0), WIND_DROP_V_POW)));
}

/**
 * Во сколько раз капля данного калибра цепляется за ветер, 1/с.
 *
 * Коэффициент подобран по картине на объекте (заказчик, 15.09.2026):
 * пятиметровую прямую струю 20 мм при ветре 15 м/с сносит примерно на 2 м,
 * десятиметровую — на 4–5 м. Прежние 0,001 давали 4,6 м уже для пятиметровой —
 * ветер выходил втрое сильнее настоящего.
 */
export const WIND_GRIP_COEF = 0.0004;

export function windGripPerSec(airDropMeters: number): number {
  return Math.min(8, WIND_GRIP_COEF / Math.max(0.0004, airDropMeters));
}

/**
 * Постоянная разгона воды ветром, с — для струи этого сопла на этой скорости
 * вылета. Больше значение — вода цепляется за воздух слабее и сносится меньше.
 *
 * Порядок величин: прямая струя 20 мм — около 14–15 с, туман — около 2 с.
 */
export function jetWindTauSec(kind: NozzleKind, widthM: number, sprayFactor: number, v0: number): number {
  const spray = clampSpray(kind, sprayFactor);
  const d = airDropM(nozzleDropM(kind, widthM, spray), spray) * speedDropFactor(v0);
  return 1 / windGripPerSec(d);
}

/**
 * То же, но калибр посчитан заранее: ветровому ограничению приходится считать
 * τ для каждой пробной высоты струи, и пересчитывать калибр по сорок раз
 * подряд незачем — от высоты зависит только поправка на скорость.
 */
export function windTauFromDrop(airDropMeters: number, v0: number): number {
  return 1 / windGripPerSec(airDropMeters * speedDropFactor(v0));
}

/** Опорная форсунка: прямая струя из сопла 20 мм с обычным распылением. */
export const REFERENCE_NOZZLE = { kind: 'straight' as NozzleKind, widthM: 0.02, sprayFactor: 0.3 };

/** Аэродинамический калибр опорной форсунки — им считаем насосы без схемы. */
export function referenceAirDropM(): number {
  const { kind, widthM, sprayFactor } = REFERENCE_NOZZLE;
  return airDropM(nozzleDropM(kind, widthM, sprayFactor), sprayFactor);
}
