/**
 * Как готовятся значения для приборов — один выбор для человека вместо двух
 * технических настроек.
 *
 * ── Зачем это здесь, а не в файле настроек ────────────────────────────────
 * Внутри это две величины: где считается воспроизведение (главный поток или
 * отдельный) и считаем ли кадры на запас вперёд. В файле настроек программы они
 * и лежат двумя полями — но человеку на объекте нельзя предлагать править
 * `app-config.json` в установленном приложении: он до него просто не доберётся.
 * Поэтому наружу выходит ОДИН список из трёх вариантов, а раскладка на поля
 * живёт здесь, в одном месте для движка и редактора.
 *
 * ── Почему три варианта, а не поле с числом ───────────────────────────────
 * Глубина запаса замерена: под нагрузкой (4 линии × 160 приборов, 16
 * секвенсоров) без запаса кадр на линии в 91 % случаев на такт устаревший, с
 * запасом 100 мс — 0 %, а 200 и 500 мс не дают уже ничего. Крутить число
 * незачем: выигрыш кончается на сотне миллисекунд, а задержка команды с
 * глубиной только растёт. Свободное поле приглашало бы искать там, где искать
 * нечего.
 *
 * ── Как названы варианты ──────────────────────────────────────────────────
 * Названия описывают УСТРОЙСТВО режима, а не историю разработки. Сначала здесь
 * было «обычный режим» и «старый режим», и заказчик справедливо заметил:
 * человек, открывший программу впервые, не знает ни про какие прежние версии, а
 * такие названия читаются как недоделка. Правила именования — `docs/ТЕРМИНЫ.md`.
 */

/** Насколько вперёд считаем значения в режиме с предрасчётом, мс. */
export const FRAME_LOOKAHEAD_MS = 100;

export type FrameMode =
  /** Отдельный поток + запас вперёд. */
  | 'ahead'
  /** Отдельный поток, но без запаса: считаем только текущий такт. */
  | 'instant'
  /** Расчёт и отправка по очереди в одном потоке. */
  | 'inline';

