/**
 * Как готовятся кадры для линии — один выбор для человека вместо двух
 * технических настроек.
 *
 * ── Зачем это здесь, а не в файле настроек ────────────────────────────────
 * Внутри это две величины: где считается воспроизведение (главный поток или
 * отдельный) и считаем ли кадры на запас вперёд. В файле настроек программы они
 * и лежат двумя полями — но человеку на объекте нельзя предлагать править
 * `app-config.json` в установленном приложении: он до него просто не доберётся.
 * Поэтому наружу выходит ОДИН список из трёх понятных вариантов, а раскладка на
 * поля живёт здесь, в одном месте для движка и редактора.
 *
 * ── Почему именно три варианта, а не поле с числом ────────────────────────
 * Глубина запаса замерена: под нагрузкой (4 линии × 160 приборов, 16
 * секвенсоров) без запаса кадр на линии в 91 % случаев на такт устаревший, с
 * запасом 100 мс — 0 %, а 200 и 500 мс не дают уже ничего. То есть крутить
 * число незачем: выигрыш кончается на сотне миллисекунд, а задержка реакции с
 * глубиной только растёт. Свободное поле приглашало бы искать там, где искать
 * нечего. Три варианта дают ровно то, что нужно на объекте: сравнить «как
 * сейчас» с «как было раньше», если что-то покажется не так.
 */

/** Насколько вперёд считаем кадры в режиме «заранее», мс. См. разбор выше. */
export const FRAME_LOOKAHEAD_MS = 100;

export type FrameMode =
  /** Отдельный поток + запас вперёд. Заводской режим. */
  | 'ahead'
  /** Отдельный поток, но без запаса: кадр считается на текущий момент. */
  | 'instant'
  /** Всё в главном потоке — как работало до 19.09.2026. */
  | 'inline';

