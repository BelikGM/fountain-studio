/** Режим → две технические величины настроек программы. */
export function frameModeToConfig(mode: FrameMode): { playbackWorker: boolean; playbackLookaheadMs: number } {
  switch (mode) {
    case 'ahead':
      return { playbackWorker: true, playbackLookaheadMs: FRAME_LOOKAHEAD_MS };
    case 'instant':
      return { playbackWorker: true, playbackLookaheadMs: 0 };
    case 'inline':
      return { playbackWorker: false, playbackLookaheadMs: 0 };
  }
}

/**
 * Две величины → режим. Нужно и для чтения настроек, и чтобы показать, что
 * РЕАЛЬНО работает: поток мог не подняться, и тогда движок сам перешёл на
 * расчёт в главном потоке (см. createPlaybackSource).
 */
export function frameModeFromConfig(playbackWorker: boolean, playbackLookaheadMs: number): FrameMode {
  if (!playbackWorker) return 'inline';
  return playbackLookaheadMs > 0 ? 'ahead' : 'instant';
}

export function frameModeLabel(mode: FrameMode): string {
  return FRAME_MODES.find((m) => m.id === mode)?.label ?? mode;
}
