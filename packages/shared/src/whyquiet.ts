/**
 * «Почему ничего не играет» — один ответ на один вопрос.
 *
 * Причин с десяток, и раньше их искали по разным вкладкам: аварийное
 * отключение — на «Диагностике», пауза — на «Отладке», стоп по расписанию — в
 * строке внизу, лицензия — под ключиком, пустое расписание — на «Расписании»,
 * а «объект не открыт» вообще нигде. На объекте это выглядело как «программа
 * сломалась».
 *
 * Здесь — чистый разбор без интерфейса: собрали факты, получили ответ. Порядок
 * причин — от самой решающей к самой мелкой: первая в списке и есть та, из-за
 * которой фонтан стоит; остальные — «а ещё обратите внимание».
 */

/** Куда вести человека за исправлением. Совпадает с вкладками редактора. */
export type QuietTab =
  | 'console'
  | 'patch'
  | 'layout'
  | 'scenes'
  | 'sequences'
  | 'show'
  | 'playlists'
  | 'schedule'
  | 'stream'
  | 'network'
  | 'settings'
  | 'license';

export interface QuietFacts {
  /** Редактор видит движок. */
  connected: boolean;
  /** Лицензия позволяет выводить на линию; reason — почему нет. */
  licensed: boolean;
  licenseReason: string;
  projectOpen: boolean;
  /** Сколько приборов в схеме объекта. */
  devices: number;
  /** Вселенные всего и сколько из них с настроенным выходом. */
  universes: number;
  universesWithOutput: number;
  /** Аварийное отключение (см. failsafe.ts). */
  failsafe: { active: boolean; reason: string };
  /** Пауза всего. */
  pausedAll: boolean;
  /** Погашено поверх всего: 'off' — стоп по расписанию, 'transition' — гашение перехода. */
  dark: 'off' | 'transition' | null;
  /** Что играет прямо сейчас. */
  sceneOn: boolean;
  sequences: number;
  showOn: boolean;
  playlistOn: boolean;
  /** Включена ли сцена покоя (когда не играет ничего другого). */
  idleSceneSet: boolean;
  /** Ветровое ограничение: 100 — не режет; correcting — уже режет. */
  windLimitPercent: number;
  windCorrecting: boolean;
  /** Сколько включённых расписаний и когда ближайшая запись («21:00», если есть). */
  schedulesEnabled: number;
  scheduleEntriesEnabled: number;
  nextEntryTime: string | null;
  /** Музыку играть нечем (нет ffmpeg), а плейлисты/расписание её ждут. */
  needsAudioPlayer: boolean;
  /** Выходы вселенных доставляют кадры (null — движок ещё не знает). */
  outputsDelivering: boolean | null;
}

export interface QuietItem {
  /** Что происходит — одной строкой, как сказал бы человек. */
  what: string;
  /** Что с этим делать. */
  fix: string;
  tab?: QuietTab;
}

export interface QuietAnswer {
  /** Движок что-то исполняет (сцена, секвенсор, шоу, плейлист). */
  playing: boolean;
  /** Главный ответ — то, что человек прочитает первым. */
  headline: string;
  items: QuietItem[];
}

export function whyQuiet(f: QuietFacts): QuietAnswer {
  const items: QuietItem[] = [];
  const playing = f.sceneOn || f.sequences > 0 || f.showOn || f.playlistOn;

  // --- Что мешает выводу вообще, даже если что-то «играет» -----------------
  if (!f.connected) {
    items.push({
      what: 'Редактор не видит движок',
      fix: 'Движок не запущен или закрыт. Запустите программу (или дождитесь автозапуска) — страница подключится сама. Фонтан при этом уже не работает: кадры приборам шлёт движок.',
    });
  }
  if (!f.projectOpen) {
    items.push({
      what: 'Объект не открыт',
      fix: 'Приборам ничего не отправляется. Откройте объект кнопкой с его именем в шапке.',
    });
  }
  if (!f.licensed) {
    items.push({
      what: 'Лицензия не даёт выводить на линию',
      fix: `${f.licenseReason || 'Лицензия не активна'}. Откройте «Лицензию» (ключик в шапке) — там ID компьютера и что делать дальше.`,
      tab: 'license',
    });
  }
  if (f.failsafe.active) {
    items.push({
      what: 'Включено аварийное отключение',
      fix: `${f.failsafe.reason || 'Причина не указана'}. Вода погашена нарочно. Разберитесь с причиной — снимется само; настройки — «Настройки» → «Аварийное отключение».`,
      tab: 'network',
    });
  }
  if (f.dark === 'off') {
    items.push({
      what: 'Стоп по расписанию — всё погашено',
      fix: 'Так и задумано до следующего запуска. Включить раньше — любой запуск руками (сцена, шоу) или запись расписания.',
      tab: 'schedule',
    });
  }
  if (f.dark === 'transition') {
    items.push({
      what: 'Гашение перед записью расписания',
      fix: 'Это несколько секунд темноты перед запуском следующей программы — дождитесь.',
      tab: 'schedule',
    });
  }
  if (f.pausedAll) {
    items.push({
      what: 'Пауза всего',
      fix: 'Картина заморожена, таймеры стоят. Снимите паузу на «Отладке» (кнопка «Продолжить»).',
      tab: 'console',
    });
  }

  // --- Играть нечему ---------------------------------------------------------
  if (f.projectOpen && f.devices === 0) {
    items.push({
      what: 'В объекте нет приборов',
      fix: 'Добавьте приборы на «Оборудовании» — без них сцены и шоу не на чем показывать.',
      tab: 'patch',
    });
  }
  if (f.projectOpen && f.universes === 0) {
    items.push({
      what: 'Не заведено ни одной вселенной DMX',
      fix: '«Настройки» → «Вселенные DMX» → «+ Вселенная», выбрать выход (Art-Net, sACN или USB-DMX) и «Применить».',
      tab: 'settings',
    });
  } else if (f.projectOpen && f.universesWithOutput === 0) {
    items.push({
      what: 'У вселенных не настроен выход',
      fix: 'Значения считаются, но уходить им некуда. «Настройки» → «Вселенные DMX»: выберите протокол и адрес, потом «Применить».',
      tab: 'settings',
    });
  } else if (f.outputsDelivering === false) {
    items.push({
      what: 'Выход не доставляет кадры',
      fix: 'Движок шлёт, но до оборудования не доходит: проверьте ноду, кабель или USB-интерфейс — «Диагностика».',
      tab: 'network',
    });
  }

  // --- Ничего не запущено ----------------------------------------------------
  if (!playing && f.projectOpen && !f.failsafe.active && f.dark !== 'off') {
    if (f.scheduleEntriesEnabled === 0) {
      items.push({
        what: 'Ничего не запущено, и расписание пустое',
        fix: 'Запустите руками: сцену на «Сценах», шоу на «Шоу» — или заведите запись на «Расписании», чтобы фонтан включался сам.',
        tab: 'scenes',
      });
    } else if (f.schedulesEnabled === 0) {
      items.push({
        what: 'Ничего не запущено: все расписания выключены',
        fix: 'Включите расписание галочкой «активно» на «Расписании» — или запустите программу руками.',
        tab: 'schedule',
      });
    } else {
      items.push({
        what: 'Ничего не запущено — ждём расписание',
        fix: f.nextEntryTime
          ? `Ближайшая запись в ${f.nextEntryTime}. Раньше — запустите руками на «Шоу» или «Сценах».`
          : 'Ближайшая запись — не сегодня (проверьте дни недели у записей). Запустить раньше можно руками.',
        tab: 'schedule',
      });
    }
    if (f.idleSceneSet) {
      items.push({
        what: 'Между программами горит «сцена, когда ничего не играет»',
        fix: 'Это не тишина: пока ничего не запущено, светит выбранная сцена. Поменять или убрать — «Настройки» → «Сцена, когда ничего не играет».',
        tab: 'settings',
      });
    }
  }

  // --- Играет, но выглядит не так -------------------------------------------
  if (f.windCorrecting || f.windLimitPercent < 100) {
    items.push({
      what: `Ветер режет струи до ${Math.round(f.windLimitPercent)} %`,
      fix: 'Так и задумано: при ветре вода летит за борт. Пороги — «Настройки» → «Ветер»; проверить без датчика — ручной ввод на «Отладке».',
      tab: 'settings',
    });
  }
  if (f.needsAudioPlayer) {
    items.push({
      what: 'Нечем играть музыку',
      fix: 'На этом компьютере нет ffmpeg: вода и свет отыграют в тишине. Установка — «Настройки» → «Громкость и тембр музыки» и памятка по установке (п. 4).',
      tab: 'settings',
    });
  }

  const headline = !f.connected
    ? 'Нет связи с движком'
    : !f.projectOpen
      ? 'Объект не открыт'
      : f.failsafe.active
        ? 'Работает аварийное отключение'
        : f.dark === 'off'
          ? 'Всё погашено стопом по расписанию'
          : f.pausedAll
            ? 'Всё на паузе'
            : playing
              ? items.length > 0
                ? 'Движок играет, но есть что проверить'
                : 'Всё работает: движок играет'
              : items.length > 0
                ? (items[0]?.what ?? 'Ничего не запущено')
                : 'Ничего не запущено';

  return { playing, headline, items };
}
