/** Общий интерфейс выхода вселенной: получает готовый кадр 512 байт каждый тик. */
export interface UniverseOutput {
  send(frame: Uint8Array): void;
  describe(): string;
  close(): void;
  /**
   * Доходят ли кадры до железа прямо сейчас — для аварийного отключения
   * (см. shared/failsafe.ts).
   *
   * Метод НЕОБЯЗАТЕЛЬНЫЙ и реализован только там, где ответ честный: у выходов
   * через USB видно, открыт ли порт и прошла ли последняя запись. Art-Net и
   * sACN идут по UDP без подтверждений — узел может быть давно выключен, а
   * отправка всё равно «успешна», поэтому они этот метод не реализуют, и
   * движок по ним о доставке не судит.
   */
  healthy?(): boolean;
}
