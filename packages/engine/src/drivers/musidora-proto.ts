import { DMX_UNIVERSE_SIZE } from '@fountain-studio/shared';

/**
 * Кадр для USB-DMX интерфейса из комплекта FontanPlay (интерфейсы USB1DMX /
 * USB2DMX / USB3DMX — по 1, 2 и 3 выхода DMX).
 *
 * Как устроен интерфейс. Внутри стоит микросхема FTDI (FT245R) и свой
 * микроконтроллер (PIC). FTDI — это только «USB-переходник»: тот самый чистый
 * драйвер FTDI, что ставится на объекте (CDM), делает из него COM-порт. А сам
 * сигнал DMX512 на линии (250 кбит/с, BREAK, развязку) строит уже
 * микроконтроллер интерфейса. Поэтому компьютеру не нужно задавать ни скорость,
 * ни BREAK — надо лишь прислать 512 значений в той обёртке, которую понимает
 * прошивка, и микроконтроллер разложит их по линии.
 *
 * Обёртка снята дизассемблером с рабочей программы FontanPlay 1.9.2.4
 * (C:\FP_60_years, версия, стоящая на объектах пользователя, 15.09.2026).
 * Порядок работы программы: FT_Open первого устройства → FT_ResetDevice →
 * FT_SetTimeouts(500, 500) → дальше только FT_Write. Ни скорости, ни BREAK,
 * ни чтения. На каждый выход шлётся отдельный кадр:
 *
 *   FF FF FF <выход> 00 <512 байт данных, значение 255 → 254> FF
 *
 *   · три 0xFF в начале и 0xFF в конце — метки кадра (следующий кадр опять
 *     начинается с трёх 0xFF, по ним прошивка и ловит границу);
 *   · <выход> — на какой из разъёмов DMX: 0xF0 первый, 0xF8 второй, 0xF9 третий;
 *   · 0x00 — стартовый код DMX;
 *   · значение 255 в данных передаётся как 254 — так делает сам FontanPlay,
 *     чтобы 0xFF оставался только меткой кадра (на яркость/ход это 0,4 %,
 *     глазом и приборами не видно).
 *
 * Длина кадра всегда 518 байт (5 + 512 + 1). FontanPlay кладёт в свой буфер
 * ещё один 0xFF, но в FT_Write передаёт ровно 518 байт (проверено по аргументу
 * длины вызова) — его и шлём.
 */

/** Команда начала кадра для выхода интерфейса 1…3 (разъём DMX). */
export const OUT_COMMAND: readonly number[] = [0xf0, 0xf8, 0xf9];

export function outCommand(out: number): number {
  const i = Math.min(OUT_COMMAND.length, Math.max(1, Math.round(out) || 1)) - 1;
  return OUT_COMMAND[i]!;
}

/** Длина готового кадра, байт. */
export const FRAME_LENGTH = 5 + DMX_UNIVERSE_SIZE + 1;

/**
 * Собрать кадр одного выхода. data — значения каналов 1…512 (короче — хвост
 * нулями). Возвращает новый Buffer: он уходит в асинхронную запись, и
 * переиспользовать его под следующий кадр нельзя.
 */
export function encodeFrame(out: number, data: Uint8Array): Buffer {
  const buf = Buffer.alloc(FRAME_LENGTH);
  let n = 0;
  buf[n++] = 0xff;
  buf[n++] = 0xff;
  buf[n++] = 0xff;
  buf[n++] = outCommand(out);
  buf[n++] = 0x00;
  for (let i = 0; i < DMX_UNIVERSE_SIZE; i++) {
    const v = i < data.length ? data[i]! : 0;
    buf[n++] = v === 0xff ? 0xfe : v;
  }
  buf[n++] = 0xff;
  return buf;
}
