/**
 * Откуда движок берёт уровни воспроизведения — общий интерфейс и протокол
 * обмена с worker-потоком.
 *
 * ── Зачем ─────────────────────────────────────────────────────────────────
 * Такты расчёта и отправки уже разделены (19.09.2026), но поток Node один: если
 * расчёт заблокирует event loop (тяжёлое шоу, сборка мусора, антивирус заморозил
 * процесс), встанут ОБА такта, и поток в линию всё равно прервётся. Полная
 * развязка — считать воспроизведение в отдельном потоке, а в главном оставить
 * только сборку кадра и отправку.
 *
 * ── Что уносится в поток, а что нет ───────────────────────────────────────
 * УНОСИТСЯ только воспроизведение: сцены, секвенсоры, шоу, плейлисты,
 * огибающие. Это самая тяжёлая часть и единственная, которая целиком
 * определяется временем.
 *
 * НЕ УНОСИТСЯ ничего, что человек крутит руками: ручная консоль, ветер,
 * служебное освещение, калибровка, тест-генератор, аварийное отключение,
 * переадресация. Они применяются в ГЛАВНОМ потоке поверх присланных уровней —
 * иначе фейдер оператора начал бы отставать на задержку обмена между потоками,
 * а «стоп» доходил бы до линии позже, чем нажат.
 *
 * ── Почему поток ведёт часы САМ ───────────────────────────────────────────
 * Если бы главный поток каждый тик присылал «посчитай на такое-то время», то
 * заблокированный главный поток остановил бы и расчёт — то есть ровно то, от
 * чего мы уходим. Поэтому у потока свой тикер и свои часы, а главный поток
 * присылает только поправки: пауза, снятие паузы и позиция звука.
 *
 * ── Как передаются кадры ──────────────────────────────────────────────────
 * Через `SharedArrayBuffer` — без копирования и без сообщений. Читать
 * полукадр нельзя, поэтому применён seqlock: перед записью поток увеличивает
 * счётчик (он становится нечётным), после записи увеличивает снова. Читатель
 * запоминает счётчик, копирует, сверяет счётчик: изменился или был нечётным —
 * значит прочитано вперемешку, берём прошлый кадр. Ни блокировок, ни ожидания:
 * главный поток никогда не встаёт в ожидании расчёта, а это и есть цель.
 */

import type { PlaybackState, Project, Show } from '@fountain-studio/shared';
import { DMX_UNIVERSE_SIZE } from '@fountain-studio/shared';

/**
 * Всё, что движку нужно от воспроизведения. Реализуют двое: `Playback` (здесь
 * же, в главном потоке — проверенный путь) и `WorkerPlayback` (в отдельном
 * потоке). Движок между ними не различает.
 */
export interface PlaybackSource {
  setUniverses(ids: number[]): void;
  setProject(project: Project): void;
  /**
   * Продвинуть воспроизведение к этому моменту. У `Playback` здесь и происходит
   * весь расчёт; у `WorkerPlayback` — только сверка часов, потому что считает
   * поток сам.
   */
  tick(nowMs: number): void;
  levels(universeId: number): Uint8Array | undefined;
  state(nowMs: number, pausedAll: boolean): PlaybackState;
  /** Растёт при любом изменении состояния — сигнал серверу разослать его. */
  readonly version: number;
  onShowAudio: ((show: Show | null) => void) | null;

  setScene(sceneId: string | null, nowMs: number): void;
  start(sequenceId: string, nowMs: number): void;
  /** Продолжить секвенсор с заданного шага — для переноса состояния при смене режима. */
  startAt(sequenceId: string, stepIndex: number, paused: boolean, nowMs: number): void;
  pause(sequenceId: string, nowMs: number): void;
  resume(sequenceId: string, nowMs: number): void;
  stop(sequenceId: string): void;
  startGroup(groupId: string, nowMs: number): void;
  stopGroup(groupId: string): void;
  pauseGroup(groupId: string, nowMs: number): void;
  resumeGroup(groupId: string, nowMs: number): void;
  stopAll(): void;
  playPlaylist(playlistId: string, itemIndex: number | undefined, nowMs: number): void;
  skipPlaylist(dir: 1 | -1, nowMs: number): void;
  stopPlaylist(): void;
  playShow(showId: string, positionMs: number, nowMs: number): void;
  pauseShow(nowMs: number): void;
  seekShow(positionMs: number, nowMs: number): void;
  syncShow(positionMs: number, nowMs: number): void;
  stopShow(): void;

  /**
   * Пауза всего: у обоих реализаций часы воспроизведения замирают. У потока
   * это надо сообщить отдельно — он ведёт часы сам.
   */
  setPausedAll(paused: boolean): void;

  /**
   * Всё ли в порядке с источником. false у `WorkerPlayback`, когда поток умер:
   * движок обязан уйти в аварийное отключение, а не тянуть последний кадр.
   * У `Playback` всегда true — ломаться там нечему отдельно от процесса.
   */
  readonly healthy: boolean;

  /** Закрыть источник (остановить поток). Для `Playback` — ничего. */
  dispose(): void;

  /**
   * Подхватить последний кадр прежнего источника при его замене.
   *
   * Зачем. Новый поток расчёта выдаёт первый кадр не сразу: ему надо
   * подняться и посчитать. Пока кадра нет, `levels` отвечает «нечего», и
   * воспроизведение в линии проваливалось в 0. Замер 22.09.2026: 50–75 мс,
   * 1–2 кадра при каждом переключении на отдельный поток. Для насоса это
   * мелочь (частотник разгоняется медленнее), а отсекатель режет воду почти
   * мгновенно — струя заметно моргала.
   *
   * Прежний кадр держится только до первого своего: как только новый
   * источник посчитал кадр, он его и перекрывает. Команда «стоп» глушит и
   * подхваченное, как и обычный кадр.
   *
   * То же с состоянием («что играет»): новый поток присылает его не сразу, и
   * до этого движок отвечал «ничего не играет». Редактор на миг показывал
   * остановку, а второе применение подряд брало это пустое состояние за
   * правду и теряло шоу. Поэтому прежнее состояние держится, пока поток не
   * пришлёт своё.
   */
  seed(levels: ReadonlyMap<number, Uint8Array>, state: PlaybackState): void;
}

// ══ Раскладка общей памяти: кольцо кадров с метками времени ════════════════

/**
 * Сколько вселенных вмещает общий буфер. 32 линии DMX — это 16 тысяч каналов,
 * столько не бывает и на очень больших объектах, а кольцо на них весит
 * считаные сотни килобайт.
 */
export const WORKER_MAX_UNIVERSES = 32;

/**
 * Насколько вперёд считаем кадры, мс (предрасчёт).
 *
 * ── Почему именно столько ─────────────────────────────────────────────────
 * Памяти буфер не стоит почти ничего: кадр — это 512 байт на линию, и секунда
 * запаса на трёх линиях весит 30 КБ. Ограничивает не память, а ЗАДЕРЖКА
 * РЕАКЦИИ: команда транспорта (запуск шоу, смена сцены) попадает в кадры не
 * раньше, чем кончится уже посчитанный запас, — потому что воспроизведение
 * нельзя отмотать назад, оно ведёт состояние шагов внутри себя.
 *
 * 100 мс — ЗАМЕРЕНО, а не на глаз. Прогон под нагрузкой (4 линии × 160
 * приборов, 16 секвенсоров, такт 50 мс) при разной глубине:
 *
 *   без запаса   — кадр на линии почти всегда на такт устаревший (91 % случаев)
 *   запас 100 мс — кадр ровно на свой момент, повторов 0 %
 *   запас 200 мс — то же, 0 %
 *   запас 500 мс — то же, 0 %
 *
 * То есть глубже 100 мс не даёт НИЧЕГО, а задержку реакции добавляет. Даже с
 * искусственными подвисаниями главного потока (по 40 мс, в 8 % тиков) сотни
 * миллисекунд хватает целиком.
 *
 * Эта задержка касается ТОЛЬКО команд человека (запустить шоу, включить
 * сцену). Уже идущее шоу она не трогает: его блоки срабатывают точно по
 * своему таймлайну, поэтому быстрая работа клапанами — очередь «как из
 * автомата» — остаётся ровной. Клапаны на объекте переключаются быстро
 * (рабочий цикл от 300 мс, отсекатели почти мгновенно), и оправдывать
 * задержку их медленностью было бы неверно: она допустима не потому, что
 * железо медленное, а потому, что это ПОСТОЯННЫЙ сдвиг одной команды, а не
 * дрожание ритма.
 *
 * Отдельно: «стоп» и снятие сцены НЕ ждут запаса. Главный поток умеет
 * заглушить вклад воспроизведения сам, немедленно (см. WorkerPlayback), — вниз
 * он может всегда, и это снимает главное возражение против предрасчёта.
 *
 * И ещё: длительность сцены на глубину запаса не влияет никак. Мы считаем
 * КАДРЫ по такту, а не сцены: сцена на 50 мс не значит «двадцать сцен в
 * буфере», она значит, что соседние кадры в буфере сильнее отличаются друг от
 * друга. Стоимость та же.
 */
export const WORKER_LOOKAHEAD_MS = 100;

/** Слова заголовка (Int32). */
export const enum WorkerHeader {
  /** Сколько ячеек в кольце. */
  Slots = 0,
  /** Сколько вселенных сейчас заполнено (пишет поток). */
  Count = 1,
  /** Шаг такта, мс — по нему главный поток считает номер ячейки. */
  TickMs = 2,
  /**
   * Сколько кадров поток посчитал всего. По нему видно, что расчёт идёт:
   * счётчик перестал расти — поток встал или умер. Переполнение int32
   * безобидно, сравнивается только «изменился или нет».
   */
  Produced = 3,
  Size = 4,
}

/** Раскладка кольца: смещения в байтах для заданного числа ячеек. */
export interface WorkerLayout {
  slots: number;
  /** Int32 на ячейку: счётчик seqlock (нечётный — идёт запись). */
  seqOffset: number;
  /** Float64 на ячейку: на какое время (стенные часы, мс) посчитан кадр. */
  targetOffset: number;
  /** Кадры: slots × WORKER_MAX_UNIVERSES × 512 байт. */
  dataOffset: number;
  bytes: number;
}

/** Сколько ячеек нужно на такой запас: сам запас плюс немного на стык. */
export function workerSlots(tickMs: number, lookaheadMs: number): number {
  return Math.max(2, Math.ceil(Math.max(0, lookaheadMs) / Math.max(1, tickMs)) + 3);
}

export function workerLayout(slots: number): WorkerLayout {
  const seqOffset = WorkerHeader.Size * 4;
  // Float64 требует выравнивания по 8 байт — поэтому округляем вверх.
  const afterSeq = seqOffset + slots * 4;
  const targetOffset = Math.ceil(afterSeq / 8) * 8;
  const dataOffset = targetOffset + slots * 8;
  return {
    slots,
    seqOffset,
    targetOffset,
    dataOffset,
    bytes: dataOffset + slots * WORKER_MAX_UNIVERSES * DMX_UNIVERSE_SIZE,
  };
}

/**
 * Номер ячейки для этого момента. Кольцо адресуется прямо по времени, поэтому
 * читателю не нужно ничего искать: он считает индекс и проверяет, что метка
 * времени в ячейке та, которую он ждёт.
 */
export function workerSlotIndex(targetMs: number, tickMs: number, slots: number): number {
  const n = Math.round(targetMs / tickMs);
  return ((n % slots) + slots) % slots;
}

/** Ближайший момент такта не позже заданного — общая для потоков сетка времени. */
export function workerGridMs(nowMs: number, tickMs: number): number {
  return Math.floor(nowMs / tickMs) * tickMs;
}

